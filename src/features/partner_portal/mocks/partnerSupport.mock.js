export const generateSupportTicketId = () => {
  _ticketSeq += 1;
  return `SUP-P-${String(_ticketSeq).padStart(4, '0')}`;
};

export const generateSupportReference = () => {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `SUP-${y}-${m}${d}-${String(_ticketSeq).padStart(3, '0')}`;
};
