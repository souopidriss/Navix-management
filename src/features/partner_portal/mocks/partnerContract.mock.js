/**
 * Comptes par statut (utilisé pour les KPI).
 */
export const getContractStatusCounts = () =>
  MOCK_PARTNER_CONTRACTS.reduce((acc, c) => {
    acc[c.status] = (acc[c.status] || 0) + 1;
    return acc;
  }, {});

/**
 * Contrats expirant dans N jours.
 * @param {number} days — nombre de jours (défaut 30)
 */
export const getExpiringContracts = (days = 30) => {
  const now = Date.now();
  const threshold = now + days * 24 * 60 * 60 * 1000;
  return MOCK_PARTNER_CONTRACTS.filter((c) => {
    if (!c.endDate) return false;
    const end = new Date(c.endDate).getTime();
    return end >= now && end <= threshold && c.status === 'active';
  });
};

/**
 * Valeur totale des contrats actifs.
 */
export const getTotalActiveContractValue = () =>
  MOCK_PARTNER_CONTRACTS
    .filter((c) => c.status === 'active')
    .reduce((sum, c) => sum + (c.value || 0), 0);
