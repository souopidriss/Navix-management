/** Retourne un trajet par son identifiant. */
export const findDriverTrip = (id) => DRIVER_TRIPS_MOCK.find((trip) => trip.id === id) ?? null;

/** Applique une mise à jour partielle à un trajet (mutation locale). */
export const updateDriverTrip = (id, patch) => {
  const trip = findDriverTrip(id);
  if (!trip) return null;
  Object.assign(trip, patch);
  return trip;
};

let notificationSequence = 0;

/**
 * Ajoute une notification en tête de liste (mock).
 * - Identifiant unique (timestamp + séquence) pour éviter les collisions.
 * - Déduplication : une notification identique (kind + titre + message)
 *   déjà présente n'est pas insérée deux fois.
 */
export const pushDriverNotification = (notification) => {
  const isDuplicate = DRIVER_NOTIFICATIONS_MOCK.some(
    (item) =>
      item.kind === notification.kind &&
      item.title === notification.title &&
      item.message === notification.message,
  );
  if (isDuplicate) return;

  notificationSequence += 1;
  DRIVER_NOTIFICATIONS_MOCK.unshift({
    id: `NTF-${Date.now()}-${notificationSequence}`,
    status: 'unread',
    ...notification,
  });
};

/** Applique une mise à jour partielle à une notification (lecture/archivage). */
export const updateDriverNotification = (id, patch) => {
  const notification = DRIVER_NOTIFICATIONS_MOCK.find((item) => item.id === id);
  if (!notification) return null;
  Object.assign(notification, patch);
  return notification;
};

