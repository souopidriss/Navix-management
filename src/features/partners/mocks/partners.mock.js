/** Pré-calcule le prochain code partenaire (ex. PRT-0016). */
export const nextPartnerCode = (() => {
  const max = MOCK_PARTNER_RECORDS.reduce((highest, record) => {
    const match = record.code.match(/(\d+)$/);
    return match ? Math.max(highest, Number(match[1])) : highest;
  }, 0);

  return String(max + 1).padStart(4, '0');
})();
